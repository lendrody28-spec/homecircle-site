"""Whisper number check for every read-aloud clip, plus the crisis 4-second rule (Sage) and the heard-audio check (Finn).
  python3 tools/ra_qc.py            -> tools/audio-qc.json and tools/audio-listen-list.md
Whisper often writes digits, so 'triple zero', 'triple 0' and '000' all count as 000."""
import json, os, re, subprocess, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools")); import ra
W = {"zero": "0", "oh": "0", "o": "0", "one": "1", "two": "2", "three": "3", "four": "4", "five": "5", "six": "6", "seven": "7", "eight": "8", "nine": "9",
     "ten": "10", "eleven": "11", "twelve": "12", "thirteen": "13", "fourteen": "14", "fifteen": "15", "sixteen": "16", "seventeen": "17", "eighteen": "18", "nineteen": "19",
     "twenty": "20", "thirty": "30", "forty": "40", "fifty": "50", "sixty": "60", "seventy": "70", "eighty": "80", "ninety": "90"}

def runs(text):
    """Transcript -> list of digit runs (adjacent number words/digits joined)."""
    t = text.lower().replace("-", " ")
    t = re.sub(r"\btriple\s*(zero|0|oh)\b", " 000 ", t)
    t = re.sub(r"\btriple\s*(\d)\b", lambda m: " " + m.group(1) * 3 + " ", t)
    toks = re.findall(r"[a-z]+|\d+|[^\sa-z\d]", t)
    out, cur = [], ""
    for i, k in enumerate(toks):
        if k == "hundred" and cur: cur += "00"; continue
        d = k if k.isdigit() else W.get(k)
        if d is not None:
            if cur and len(d) == 2 and d.endswith("0") and False: pass
            cur += d; continue
        if k in (",", ".") and cur and i + 1 < len(toks) and (toks[i + 1].isdigit() or toks[i + 1] in W): continue
        if cur: out.append(cur); cur = ""
    if cur: out.append(cur)
    return out

def expected(text):
    t = re.sub(r"1800RESPECT", "1800", text)
    return [re.sub(r"\D", "", n) for n in re.findall(r"\d[\d ]*\d|\d", t)]

def main():
    m = ra.load(); jobs = []
    for l in m["lines"]:
        for v, c in l["clips"].items(): jobs.append({"file": str(ra.AUDIO / c["file"]), "id": l["id"], "voice": v, "text": l["text"]})
    py = os.environ.get("WHISPER_PY", "/workspace/tts-venvs/whisper/bin/python")
    r = subprocess.run([py, str(ROOT / "tools" / "tts" / "whisper_check.py")], input=json.dumps([{"file": j["file"]} for j in jobs]), capture_output=True, text=True, check=True)
    res = {x["file"]: x for x in json.loads(r.stdout)}
    report, fails, crisis = [], [], []
    for j in jobs:
        w = res[j["file"]]; got = runs(w["text"]); exp = expected(j["text"])
        missing = [e for e in exp if not any(e in g for g in got)]
        row = {"id": j["id"], "voice": j["voice"], "file": Path(j["file"]).name, "heard": w["text"], "expectedNumbers": exp, "missingNumbers": missing}
        if j["id"].startswith("kai.crisis."):
            t0 = None; ws = w["words"]
            for i, (wd, s, e) in enumerate(ws):
                a = wd.strip().lower().strip(".,")
                nxt = ws[i + 1][0].strip().lower().strip(".,") if i + 1 < len(ws) else ""
                if re.search(r"000|triple.?(zero|0)", a) or (a == "triple" and nxt in ("zero", "0", "oh")):
                    t0 = s; break
            row["tripleZeroAt"] = t0; row["tripleZeroWithin4s"] = t0 is not None and t0 <= 4.0
            crisis.append(row)
        heard = w["text"].strip()
        row["heardEmpty"] = not re.search(r"[a-z0-9]", heard, re.I)
        if j["id"].startswith("kai.crisis."):
            row["heardCall"] = bool(re.search(r"\bcall\b", heard, re.I))
            row["heardFail"] = row["heardEmpty"] or not row["heardCall"] or bool(missing) or not row["tripleZeroWithin4s"]
        else:
            row["heardFail"] = row["heardEmpty"]
        if missing or row["heardFail"]: fails.append(row)
        report.append(row)
    (ROOT / "tools" / "audio-qc.json").write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n")
    print(f"clips checked: {len(report)}; number misses: {sum(1 for r in report if r['missingNumbers'])}")
    for c in crisis: print(f"  crisis {c['id']} [{c['voice']}]: triple zero at {c['tripleZeroAt']}s -> {'OK' if c['tripleZeroWithin4s'] else 'FAIL'}")
    for f in fails: print("  FLAG", f["id"], f["voice"], f["file"], "missing", f["missingNumbers"], "| heard:", f["heard"][:160])
    hf = [r for r in report if r["heardFail"]]
    print(f"heard-audio check: {'PASS' if not hf else 'FAIL'} ({len(hf)} failing: crisis clips missing call/numbers/4 s, or empty transcripts)")
    for r in hf: print("  HEARD-FAIL", r["id"], r["voice"], r["file"], "| heard:", r["heard"][:120])
    listen(report, m)
    return report

def listen(report, m):
    """tools/audio-listen-list.md: every clip whisper queried, for a human listen-through."""
    names = {k: f"{v.get('engine')} {v.get('voice')}" for k, v in m["voices"].items()}
    out = ["# Read-aloud listen-through list (DRAFT clips)", "",
           "Generated by `tools/ra_qc.py` from `tools/audio-qc.json`. Play each clip in `assets/audio/` and tick it if it sounds right and says every number correctly. "
           "Spoken scripts are in `tools/audio-manifest.json`. " + ", ".join(f"Voice {k} = {v}" for k, v in names.items()) + ".", "",
           "Whisper (base, CPU) often mishears names and long numbers, so a flag here means listen, not that the audio is wrong.", ""]
    for title, pick in (("Crisis clips (must pass: says call, every number, triple zero within 4 s)", lambda r: r["id"].startswith("kai.crisis.")),
                        ("Other clips", lambda r: not r["id"].startswith("kai.crisis."))):
        rows = [r for r in report if pick(r)]
        out += ["## " + title, ""]
        for r in rows:
            if not (r["missingNumbers"] or r["heardFail"]) and not r["id"].startswith("kai.crisis."): continue
            why = []
            if r.get("heardEmpty"): why.append("empty transcript")
            if r["id"].startswith("kai.crisis."): why.append(f"triple zero at {r['tripleZeroAt']}s")
            if r["missingNumbers"]: why.append("numbers not matched: " + ", ".join(r["missingNumbers"]))
            out.append(f"- [ ] {r['file']} - {r['id']} [{r['voice']}] - {'; '.join(why) or 'ok'} - heard: \"{r['heard'][:140]}\"")
        out.append("")
    out += ["## Held back pending human listen", "", "Not in the build (files kept outside the site in /workspace/tts-work/held/). Until a person listens and signs off, these read with the device's own voice.", ""]
    for l in m["lines"]:
        for v, c in l.get("clipsHeld", {}).items():
            use = "Voice A clip used for both voices" if l.get("clips", {}).get(v, {}).get("sharedFrom") else "device voice"
            out.append(f"- [ ] {c['file']} - {l['id']} [{v}] - held back pending human listen; now: {use}")
    out += ["", "## Human-listened", ""]
    for l in m["lines"]:
        for v, note in l.get("listened", {}).items():
            out.append(f"- [x] {l['clips'][v]['file']} - {l['id']} [{v}] - {note}")
    out.append("")
    ok = {l["clips"][v]["file"]: n for l in m["lines"] for v, n in l.get("listened", {}).items()}
    out = [("- [x] " + x[6:] + f" -> {ok[x[6:].split(' ')[0]]}") if x.startswith("- [ ] ") and x[6:].split(" ")[0] in ok else x for x in out]
    (ROOT / "tools" / "audio-listen-list.md").write_text("\n".join(out))

def retake(rows, tries=4):
    """Re-record flagged Melo (Voice A) clips: same settings and name, the engine's randomness gives a new take.
    Kokoro is deterministic, so its flags need a script change instead."""
    import hashlib
    m = ra.load()
    for t in range(tries):
        bad = [r for r in rows if (r["missingNumbers"] or r["heardFail"] or re.search(r"\b(core|court|cool)\b", r["heard"], re.I))
               and m["voices"][r["voice"]]["engine"] == "melo"]
        if not bad: break
        print(f"retake round {t + 1}: {len(bad)} clips")
        by_v = {}
        for r in bad:
            l = next(x for x in m["lines"] if x["id"] == r["id"]); by_v.setdefault(r["voice"], []).append((l["spoken"], str(ra.AUDIO / r["file"])))
        for v, jobs in by_v.items(): ra.synth(m["voices"][v], list(dict(jobs).items()))
        rows = main()
    for l in m["lines"]:
        for v, c in l["clips"].items():
            f = ra.AUDIO / c["file"]; c["bytes"] = f.stat().st_size; c["sha256"] = hashlib.sha256(f.read_bytes()).hexdigest()
    ra.MANIFEST.write_text(json.dumps(m, indent=1, ensure_ascii=False) + "\n")
    return rows

if __name__ == "__main__":
    rows = main()
    if "--retake" in sys.argv: rows = retake(rows)
    sys.exit(1 if any(r["heardFail"] for r in rows) else 0)
